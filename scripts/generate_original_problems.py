def s(count):
    return 's' * count


def square(size):
    return (s(size) + 'r') * 4


def trace(start, commands, walls=(), bounded=True):
    x, y = start
    heading = 0
    points = []
    for command in commands:
        if command == 's':
            dx, dy = [(0, -1), (1, 0), (0, 1), (-1, 0)][heading]
            nx, ny = x + dx, y + dy
            if (nx, ny) not in walls:
                if bounded:
                    assert 0 <= nx < 25 and 0 <= ny < 25, (start, nx, ny)
                x, y = nx, ny
            points.append((x, y))
        else:
            heading = (heading + (1 if command == 'r' else -1)) % 4
    return points


